"""
СЕДЬМОЙ ПРОХОД. Патчи 1-4 по итогам прогона первого исполнителя (то же 12 случаев).

ПАТЧ 1 (П3 в верной форме):
    «Смена шагов МОЖЕТ сменить выход» — аксиома.
    «Тот же выход при изменённых шагах» — не опровержение и не норма,
    а ПОВОД: эквивалентность последовательностей доказывается или
    отмечается явно. Сходство выхода само себя не верифицирует.
ПАТЧ 2 (критерий закрыт предусловиями):
    ВЕРИФИЦИРОВАНО = предусловия выполнены и сверяемы
                    ∧ двое независимых с нуля сошлись
                    ∧ сходство сверено с критерием выхода.
    Без первого слагаемого — ПУСТО. Без третьего — НЕСВЕРЯЕМО.
ПАТЧ 3 (возвращён третий вердикт):
    UNKNOWN = «не сошлись без вины» (предел точности прибора,
    закрытое наблюдение). «Сошлись / не сошлись» — не полное
    множество исходов; ложный ярлык хуже отсутствия ярлыка.

ПАТЧ 4 (найден при ИНТЕГРАЦИИ, не при прогоне):
    Комбинаторика вердиктов предсказала незанятую клетку: двое
    независимых с нуля СОШЛИСЬ — но не на том, что заявлено критерием
    (сходство да, предусловия чисты, сверка состоялась и НЕ пройдена).
    Это не «?» и не пусто: расхождение не между исполнителями, а между
    исполнением и ожиданием — вердикт СОГЛАСОВАНО-НЕВЕРНО -> ЗАПЛАТ-6.

В каждом прогоне — два независимых исполнителя: два разных кодовых пути.
Среды: чистые и дефектные. Судья — ручной: категории ниже не самопроверка,
а демонстрация; ломать на своих средах — работа ВТОРОГО ИСПОЛНИТЕЛЯ.
"""

rows = []


def verdict_v6(agree):
    # буквально по сухому остатку v6: сошлись = верифицировано
    return "верифицировано" if agree else "не верифицировано"


def verdict_v7(precond, agree, crit, honest):
    # патчи 2+3: предусловия -> сходство -> сверка; не сошлись без вины -> UNKNOWN
    if honest is None:                       # трасса ЗАПЛАТ-6, не прогон исполнителей
        return "ПРОТОКОЛ ЛОВИТ"
    if precond is False:                     # патч 2: сходство вне предусловий пусто
        return "ПУСТО"
    if agree and crit is True:
        return "ВЕРИФИЦИРОВАНО"
    if agree and crit is None:               # патч 2: сверка с критерием невозможна
        return "НЕСВЕРЯЕМО"
    if agree and crit is False:              # патч 4: сошлись — но не на том
        return "СОГЛАСОВАНО-НЕВЕРНО -> ЗАПЛАТ-6"
    if not agree:
        return "UNKNOWN" if honest else "ДЕФЕКТ -> ЗАПЛАТ-6"   # патч 3
    return "?"


def add(case, point, precond, agree, crit, honest, note):
    rows.append((case, point, precond, agree, crit, honest, note))


# ================= КОНТРОЛЬ: чистая среда, предусловия выполнены (П2) =================

def add2_a():
    return 2 + 2


def add2_b():
    x = 2
    for _ in range(2):
        x += 1
    return x


a, b = add2_a(), add2_b()
add("2+2", "П2", True, a == b, (a == 4 and b == 4), True,
    "двое с нуля сошлись; сверка с критерием возможна — эталонный случай")


def gcd_mod(x, y):
    while y:
        x, y = y, x % y
    return x


def gcd_sub(x, y):
    while x != y:
        if x > y:
            x -= y
        else:
            y -= x
    return x


a, b = gcd_mod(48, 18), gcd_sub(48, 18)
add("НОД(48,18)", "П2", True, a == b, (a == 6 and b == 6), True,
    "остатки против вычитания — независимые пути сошлись")


def sort_a(lst):
    return sorted(lst)


def sort_b(lst):
    r = list(lst)
    for i in range(1, len(r)):
        v = r[i]
        j = i - 1
        while j >= 0 and r[j] > v:
            r[j + 1] = r[j]
            j -= 1
        r[j + 1] = v
    return r


a, b = sort_a([3, 1, 2]), sort_b([3, 1, 2])
add("сортировка [3,1,2]", "П2", True, a == b, (a == [1, 2, 3] and b == [1, 2, 3]), True, "")

T = [[0.7, 0.3], [0.4, 0.6]]


def markov_iter(v, n):
    for _ in range(n):
        v = [v[0] * T[0][0] + v[1] * T[1][0], v[0] * T[0][1] + v[1] * T[1][1]]
    return v


def markov_pow(v, n):
    P = [[1.0, 0.0], [0.0, 1.0]]
    for _ in range(n):
        P = [[P[i][0] * T[0][j] + P[i][1] * T[1][j] for j in range(2)] for i in range(2)]
    return [v[0] * P[0][j] + v[1] * P[1][j] for j in range(2)]


a = markov_iter([1.0, 0.0], 3)
b = markov_pow([1.0, 0.0], 3)
ok = all(abs(x - y) < 1e-12 for x, y in zip(a, b))
crit = abs(a[0] - 0.583) < 1e-12 and abs(a[1] - 0.417) < 1e-12
add("цепь Маркова, 3 шага", "П2", True, ok, crit, True,
    "итерации против степени матрицы: 0.583/0.417, двое сошлись")


# ================= ГРАНИЦА ПРЕДУСЛОВИЙ (П2) — патч 2 закрывает дыру =================

class Garment:
    def __init__(self, button_ok):
        self.button_ok = button_ok
        self.unbuttoned = False
        self.removed = False


def door_a(g):
    acts = 0
    g.unbuttoned = g.unbuttoned or g.button_ok
    acts += 1
    if g.unbuttoned:
        g.removed = True
    acts += 1
    return g.removed, acts


def door_b(g):
    acts = 0
    if g.button_ok:
        g.unbuttoned = True
    acts += 1
    if g.unbuttoned:
        g.removed = True
    acts += 1
    return g.removed, acts


g1, g2 = Garment(False), Garment(False)
ra, na = door_a(g1)
rb, nb = door_b(g2)
add("дверь: расстегни—сними, пуговица сломана", "П2/П4", False, ra == rb, (ra and rb), True,
    "оба действия исполнены (%d и %d шагов), выхода нет; предусловие «застёжка исправна» нарушено. "
    "v6 звал это «верифицировано» — теперь ПУСТО" % (na, nb))


class Oven:
    def __init__(self, power):
        self.power = power
        self.baked = False


def bake_a(o):
    o.baked = bool(o.power)
    return o.baked


def bake_b(o):
    if o.power:
        o.baked = True
    return o.baked


oa, ob = Oven(False), Oven(False)
ra, rb = bake_a(oa), bake_b(ob)
add("хлеб: замесить—выпекать, духовка обесточена", "П2/П4", False, ra == rb, (ra and rb), True,
    "двое с нуля сошлись на «сырой»: сходство есть, выхода нет — ПУСТО")


# ================= П3 В ВЕРНОЙ ФОРМЕ (патч 1) =================

class Room:
    def __init__(self):
        self.on = False


def light_seq_a(r):          # вкл; щелк; щелк
    r.on = True
    r.on = not r.on
    r.on = not r.on
    return r.on


def light_seq_b(r):          # вкл
    r.on = True
    return r.on


ra = light_seq_a(Room())
rb = light_seq_b(Room())
add("свет: [вкл;щёлк;щёлк] против [вкл]", "П3", True, ra == rb, (ra and rb), True,
    "шаги сменили — выход тот же: по патчу 1 это ПОВОД, эквивалентность доказана "
    "(двойной щелчок — инволюция, триtoggle = один); v6 вешал «ОПРОВЕРГНУТ»")


