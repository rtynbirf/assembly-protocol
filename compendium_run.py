# ================= КРИТЕРИЙ «ДВОЕ СОШЛИСЬ» И UNKNOWN (патч 3) =================

def logistic_pair(xa, xb, n=50, r=3.9, tol=0.1):
    step = None
    for i in range(1, n + 1):
        xa = r * xa * (1 - xa)
        xb = r * xb * (1 - xb)
        if step is None and abs(xa - xb) > tol:
            step = i
    return xa, xb, step


xa, xb, div = logistic_pair(0.2, 0.2 + 1e-9)
add("логист. карта, 50 шагов: x0=0.2 против x0=0.2+1e-9", "П4", True,
    abs(xa - xb) < 1e-9, None, True,
    "одна запись шагов, «одно» начальное состояние в пределах точности прибора 1e-9; "
    "выходы %.4f и %.4f, расхождение >0.1 на шаге %d. Не сойдутся НИКОГДА — и бага нет: "
    "предел точности состояния. v6 вешал «не верифицировано» — теперь UNKNOWN" % (xa, xb, div))

