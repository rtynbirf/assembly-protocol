# ================= ЗАПЛАТ-6 (трассы, не прогоны) =================

def zaplat6_bread(o):
    steps = []
    expected, got = "испечён", ("испечён" if o.power else "сырой")
    if expected != got:
        steps.append("1. расхождение: ожидали «%s», получили «%s»" % (expected, got))
        if not o.power:
            steps.append("2. условия: питание духовки отсутствует — КОРЕНЬ найден, "
                         "исполнение и реализация не при чём")
            return steps
        steps.append("3. исполнение: проверка шагов")
    return steps


