#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ЛЕТОПИСЬ-СТРАЖ: конечный автомат.

Не текст О летописи, а исполнитель закона дома «ТЫ ВСЁ И ВСЯ СВЯЗАЛ? ТАМ ВСЁ БЬЁТСЯ?»:
  - вердикты — состояния автомата (терминальные); порядок расследования —
    таблица переходов, перескочить нельзя;
  - три поверхности правды: летопись (versions.json -> летопись), CHANGELOG
    (записи-заголовки), заявки коммит-сообщений («CHANGELOG С184–С187»);
  - сверка честна внутри эпохи конвенции (эра = наименьший СN заголовков
    CHANGELOG); за границей эпохи автомат не молчит — он возвращает примечание.

Реальные дыры дома, на которых механизм обязан отказать (фикстуры байт-в-байт
в страж_фикстуры/): С184/С185 (ходы в летописи, записей не существовало),
С178 (то же, найдено стражем при сборке), заявки С186/С187 «CHANGELOG С184/
С185/С186» против пустого файла.

Запуск: python3 летопись_fsm.py [путь_репо] [--само] [--коммиты N]
  exit 0 — ЛЕТОПИСЬ ЦЕЛА / ГОЛО; exit 1 — ДРЕЙФ ЕСТЬ / НЕСВЕРЯЕМО.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
import shutil
from collections import Counter

EXIT_OK, EXIT_ДРЕЙФ = 0, 1

РЭ_СН = re.compile(r'С(\d+)')
РЭ_ЗАНЯТИЕ = re.compile(r'^##\s+Task\s+(\d+)', re.M | re.I)
РЭ_ЗАЯВКА = re.compile(
    r'CHANGELOG[:\s]+((?:С\d+)\s*(?:[–\-/,+]*\s*(?:С\d+))*)', re.I)
РЭ_ДИАПАЗОН = re.compile(r'(С\d+)\s*[–\-]\s*(?:С?)(\d+)')

ЛЕТОПИСЬ_ФАЙЛЫ = ('CHANGELOG.md', 'data/versions.json', 'worklog.md', 'CHRONICLE.md')


class ЛетописьНарушение(Exception):
    pass


TABLE = {
    ("СБОР", "собрано"): "ИЗВЛЕЧЕНИЕ",
    ("СБОР", "голая"): "ГОЛО",
    ("ИЗВЛЕЧЕНИЕ", "разобрано"): "СВЕРКА",
    ("ИЗВЛЕЧЕНИЕ", "сломано"): "НЕСВЕРЯЕМО",
    ("СВЕРКА", "сходится"): "ЛЕТОПИСЬ ЦЕЛА",
    ("СВЕРКА", "дрейф"): "ДРЕЙФ ЕСТЬ",
}
ТЕРМИНАЛЫ = ("ЛЕТОПИСЬ ЦЕЛА", "ДРЕЙФ ЕСТЬ", "ГОЛО", "НЕСВЕРЯЕМО")


class СтражFSM:
    """Переходы только по TABLE. Чужой переход — ЛетописьНарушение."""

    def __init__(self):
        self.state = "СБОР"
        self.trace = []
        self.дыры = []        # расхождения (вердикт-члены)
        self.примечания = []  # честные границы прогона
        self._летопись_строки = []
        self.лимит_коммитов = 40

    def fire(self, event):
        key = (self.state, event)
        if key not in TABLE:
            raise ЛетописьНарушение("незаконный переход: %s --%s--> ?" % key)
        self.state = TABLE[key]
        self.trace.append("%s --%s--> %s" % (key[0], event, self.state))
        return self.state

    def verdict(self):
        return self.state if self.state in ТЕРМИНАЛЫ else None

    # ── СБОР: топология летописей репо ──
    def собрать(self, корень):
        топ = {}
        for имя in ЛЕТОПИСЬ_ФАЙЛЫ:
            п = os.path.join(корень, имя)
            if os.path.isfile(п):
                топ[имя] = п
        заявки = []
        if os.path.isdir(os.path.join(корень, '.git')):
            try:
                out = subprocess.check_output(
                    ['git', '-C', корень, 'log', '--format=%H%x00%s',
                     '-n', str(self.лимит_коммитов)],
                    stderr=subprocess.DEVNULL).decode('utf-8', 'replace')
                for строка in out.splitlines():
                    if '\x00' in строка:
                        ша, сабж = строка.split('\x00', 1)
                        заявки.append((ша, сабж))
            except Exception:
                self.примечания.append('git-история нечитаема — заявки коммитов не сверены')
        топ['заявки'] = заявки
        if not any(имя in топ for имя in ЛЕТОПИСЬ_ФАЙЛЫ):
            self.fire('голая')
        else:
            self.fire('собрано')
        return топ

    # ── ИЗВЛЕЧЕНИЕ ──
    def извлечь(self, топ):
        извл = {'записи': {}, 'занятия': {}, 'летопись': set(), 'эра': None}
        if 'CHANGELOG.md' in топ:
            текст = open(топ['CHANGELOG.md'], encoding='utf-8', errors='replace').read()
            # грамматика адресов дома: запись адресует ход, если заголовок —
            # «ЛАТКА/Латка/ЛАТКИ СN…» (все СN строки — адреса) или несёт
            # скобочный адрес «(СN,…)» («## [11.41] «ДОСТУПНО» — (С119, ключ…)»,
            # «## [Такт v11.50] «НАПОЛНЕНИЕ» (С139, RUM23-8)»). СN вне этой
            # грамматики («закон С128 завершён…») — ссылки, не адреса.
            заголовки = re.findall(r'^##\s+(.+)$', текст, re.M)
            порядок = []
            for заг in заголовки:
                адреса = set()
                if re.search(r'латк', заг, re.I):
                    адреса |= {int(m) for m in РЭ_СН.findall(заг)}
                адреса |= {int(m) for m in re.findall(r'[(]\s*С(\d+)\s*[);,–\-]', заг)}
                for ч in адреса:
                    извл['записи'][ч] = извл['записи'].get(ч, 0) + 1
                if адреса:
                    порядок.append(max(адреса))
            if порядок:
                извл['эра'] = min(извл['записи'])
                for i in range(1, len(порядок)):
                    if порядок[i] >= порядок[i - 1]:
                        self.примечания.append(
                            'порядок адресных записей: С%d идёт после С%d — история дома знает честные СТОП-ГОРН и репарации (примечание, не дыра)'
                            % (порядок[i], порядок[i - 1]))
                дуб = {ч for ч, к in извл['записи'].items() if к > 1}
                if дуб:
                    self.примечания.append(
                        'СN упомянуты в нескольких записях: %s — дом пишет записи-спутники сознательно (примечание, не дыра)'
                        % ', '.join('С%d' % ч for ч in sorted(дуб)))

        if 'data/versions.json' in топ:
            try:
                данные = json.load(open(топ['data/versions.json'], encoding='utf-8'))
            except Exception as e:
                self.дыры.append('versions.json не разбирается: %s' % str(e)[:80])
                self.fire('сломано')
                return извл
            for такт in данные.get('летопись', []) if isinstance(данные, dict) else []:
                for с in такт.get('сделано', []) if isinstance(такт, dict) else []:
                    self._летопись_строки.append(str(с))
                    извл['летопись'] |= {int(m) for m in РЭ_СН.findall(str(с))}

        if 'worklog.md' in топ:
            текст = open(топ['worklog.md'], encoding='utf-8', errors='replace').read()
            счёт = Counter(int(m) for m in РЭ_ЗАНЯТИЕ.findall(текст))
            for ч, к in счёт.items():
                if к > 1:
                    self.дыры.append('worklog.md: Task %d упомянут %d раз (запись одна)' % (ч, к))
                извл['занятия'][ч] = к

        if 'CHRONICLE.md' in топ:
            текст = open(топ['CHRONICLE.md'], encoding='utf-8', errors='replace').read()
            счёт = Counter(re.findall(r'^##\s+\[([^\]]{1,40})\]', текст, re.M))
            for заг, к in счёт.items():
                if к > 1:
                    self.дыры.append('CHRONICLE.md: запись «%s…» %d раз (запись одна)' % (заг, к))

        self.fire('разобрано')
        return извл

    # ── СВЕРКА ──
    def сверить(self, извл, заявки):
        записи = извл.get('записи', {})
        летопись = извл.get('летопись', set())
        М = sorted(записи)

        # нестабильные номера: летопись сама декларирует перенумеровки
        # («перенумеровано честно С98→С104», «С99→С100») — в их диапазоне ±1
        # нумерация переобъявлялась, зуб-правило там не применимо (граница прибора)
        нестабильные = set()
        if self._летопись_строки:
            for с in self._летопись_строки:
                if re.search(r'С\d+\s*→|→\s*С\d+', с):
                    for m in РЭ_СН.findall(с):
                        n = int(m)
                        нестабильные |= {n - 1, n, n + 1}

        # Р1 «ЗУБ»: между соседними адресными записями (разрыв ≤ 5 — параметр дома:
        # больший разрыв — граница эры, где записи адресуются иначе, а не дыра)
        # каждый ход летописи обязан иметь запись — кроме нестабильных номеров.
        for i in range(len(М) - 1):
            a, b = М[i], М[i + 1]
            if b - a <= 5:
                for n in range(a + 1, b):
                    if n in летопись and n not in записи:
                        if n in нестабильные:
                            self.примечания.append('С%d: внутри зоны честных перенумеровок дома — зуб не применим (примечание)' % n)
                        else:
                            self.дыры.append('С%d: ход в летописи есть, адресные соседи С%d и С%d есть — записи в CHANGELOG нет' % (n, a, b))
            else:
                self.примечания.append('разрыв адресных записей С%d..С%d — граница эры конвенции (не проверяется)' % (a, b))

        # Р2 «НОВЕЕ НОВЕЙШЕГО»: ход новее последней записи обязан быть записан
        if М and летопись:
            for n in sorted(n for n in летопись if n > М[-1]):
                self.дыры.append('С%d: ход новее последней записи С%d — записи в CHANGELOG нет' % (n, М[-1]))

        for ша, сабж in заявки or []:
            м = РЭ_ЗАЯВКА.search(сабж)
            if not м:
                continue
            заявленное = set()
            д = РЭ_ДИАПАЗОН.search(м.group(1))
            if д:
                заявленное |= set(range(int(д.group(1)[1:]), int(д.group(2)) + 1))
            заявленное |= {int(m2) for m2 in РЭ_СН.findall(м.group(1))}
            for n in sorted(заявленное):
                if записи and n not in записи:
                    self.дыры.append('коммит %s заявляет «CHANGELOG С%d» — записи в файле нет' % (ша[:7], n))
                elif not записи:
                    self.примечания.append('коммит %s заявляет С%d — конвенции записей в репо нет, сверить нечем' % (ша[:7], n))

        if self.дыры:
            self.fire('дрейф')
        else:
            self.fire('сходится')

    def прогон(self, корень, заявки=None):
        self._топ_имена = set()
        топ = self.собрать(корень)
        self._топ_имена = {имя for имя in ЛЕТОПИСЬ_ФАЙЛЫ if имя in топ}
        if self.verdict() == 'ГОЛО':
            return self.отчёт()
        if заявки is not None:
            топ['заявки'] = заявки
        извл = self.извлечь(топ)
        if self.verdict() == 'НЕСВЕРЯЕМО':
            return self.отчёт()
        self.сверить(извл, топ.get('заявки'))
        return self.отчёт()

    def отчёт(self):
        print('АВТОМАТ: %s' % ' -> '.join(self.trace))
        print('ВЕРДИКТ: %s' % self.verdict())
        for д in self.дыры:
            print('  ДЫРА: %s' % д)
        for п in self.примечания:
            print('  ПРИМЕЧАНИЕ: %s' % п)
        return self.verdict()


