    print("АВТОМАТ ЛЕТОПИСИ: векторы %d/%d; незаконные переходы пойманы %d/%d;"
          % (ok, len(VECTORS), caught, n_illegal))
    print("  все 4 вердикта достижимы: %s" % ("да" if all_reachable else "НЕТ"))
    if fail or not all_reachable:
        print("ПРОВАЛ: %d" % len(fail))
        return 1
    print("МЕХАНИЗМ ИСПОЛНЕН: 0 провалов. Дом = реестру, заявки не врут.")
    return EXIT_OK


