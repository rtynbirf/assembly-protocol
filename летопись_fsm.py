def fresh():
    return СтражFSM()


def дойди(*события):
    m = fresh()
    for e in события:
        m.fire(e)
    return m


def to_extracted():
    m = fresh()
    m.fire('собрано')
    m.fire('разобрано')
    return m


def to_verdict(name):
    пути = {'ГОЛО': ['голая'], 'НЕСВЕРЯЕМО': ['собрано', 'сломано'],
            'ЛЕТОПИСЬ ЦЕЛА': ['собрано', 'разобрано', 'сходится'],
            'ДРЕЙФ ЕСТЬ': ['собрано', 'разобрано', 'дрейф']}
    m = fresh()
    for e in пути[name]:
        m.fire(e)
    return m


def прогон_вектор(файлы):
    дир = tempfile.mkdtemp(prefix='страж_вектор_')
    try:
        заявки = None
        for имя, тело in файлы.items():
            if имя == 'заявка':
                заявки = [('0000000', тело)]
                continue
            п = os.path.join(дир, имя)
            os.makedirs(os.path.dirname(п), exist_ok=True)
            with open(п, 'w', encoding='utf-8') as f:
                f.write(тело)
        m = СтражFSM()
        вер = m.прогон(дир, заявки=заявки)
        return вер, len(m.дыры)
    finally:
        shutil.rmtree(дир, ignore_errors=True)


